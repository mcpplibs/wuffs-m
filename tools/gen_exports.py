#!/usr/bin/env python3
"""Write the module units of mcpplibs.mwrap.wuffs from wuffs-v0.3.c.

  src/<package>.cppm   mcpplibs.mwrap.wuffs.<package>, one per upstream package
                       (base, adler32, bmp … zlib): every type, struct tag,
                       function and status message / table of the package by
                       `export using` (the upstream globals, unchanged), and its
                       `static inline` API adapted (below). Each re-exports base.
  src/wuffs_aux.cppm   mcpplibs.mwrap.wuffs.aux: the C++ API, namespace
                       wuffs_aux and wuffs_aux::sync_io, by `using`.
  src/macros.cppm      mcpplibs.mwrap.wuffs.macros: every macro that is a
                       constant, in mcpplibs::mwrap::wuffs::macros under its
                       name; the macros that name a function, as pointers to it.
  src/wuffs.cppm       mcpplibs.mwrap.wuffs: re-exports all of the above.

THE static inline API. Wuffs declares ~300 helpers `static inline`
(wuffs_base__make_slice_u8, wuffs_base__pixel_format__bits_per_pixel …).
Internal linkage cannot be exported, so each is adapted in namespace
mcpplibs::mwrap::wuffs under the same name and signature, calling upstream's
own. The adapters are defined in the interface but not `inline`: an inline
body calling an internal-linkage function would expose it to importers.

With --check, nothing is written and a difference fails.
"""
import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory import Function, HEADER, fetch, find_clang, surface  # noqa: E402

BANNER = '// Generated by tools/gen_exports.py from wuffs-v0.3.c (Wuffs 0.3.6) — do not\n// edit by hand.'
NAMESPACE = 'mcpplibs::mwrap::wuffs'


def declarator(type_: str, name: str) -> str:
    if '(*)' in type_:
        return type_.replace('(*)', f'(*{name})', 1)
    if type_.endswith(']'):
        at = type_.index('[')
        return f'{type_[:at].rstrip()} {name}{type_[at:]}'
    return f'{type_} {name}'


def adapter(f: Function) -> str:
    params = ', '.join(declarator(t, n) for t, n in f.params)
    args = ', '.join(n for _, n in f.params)
    return f'auto {f.name}({params}) -> {f.result} {{ return ::{f.name}({args}); }}'


def package_unit(sf, pkg: str) -> str:
    out = [BANNER, '//',
           f'// mcpplibs.mwrap.wuffs.{pkg} — Wuffs\' {pkg} package. Every name below is the',
           f'// upstream global of <{HEADER}>, unchanged; the static inline functions are',
           f'// adapted in {NAMESPACE} under the same names (see tools/gen_exports.py).',
           'module;', f'#include <{HEADER}>', '', f'export module mcpplibs.mwrap.wuffs.{pkg};', '']
    if pkg != 'base':
        out += ['export import mcpplibs.mwrap.wuffs.base;', '']
    for title, names in (('types', sf.types.get(pkg, [])), ('struct tags', sf.tags.get(pkg, [])),
                         ('functions', sf.functions.get(pkg, [])),
                         ('status messages and tables', sf.data.get(pkg, []))):
        if names:
            out.append(f'// {title} ({len(names)})')
            out += [f'export using ::{n};' for n in names]
            out.append('')
    inlines = sf.inlines.get(pkg, [])
    if inlines:
        out.append(f'// the static inline API ({len(inlines)}), adapted: each calls upstream\'s own')
        out.append(f'export namespace {NAMESPACE} {{')
        out += [adapter(f) for f in inlines]
        out.append(f'}}  // namespace {NAMESPACE}')
    return '\n'.join(out).rstrip() + '\n'


def aux_unit(sf) -> str:
    out = [BANNER, '//',
           '// mcpplibs.mwrap.wuffs.aux — wuffs_aux, Wuffs\' C++ API (DecodeImage,',
           '// DecodeJson, DecodeCbor, sync_io::Input …), the upstream names unchanged.',
           '// compat.wuffs compiles the implementation as C++, which defines it.',
           'module;', f'#include <{HEADER}>', '', 'export module mcpplibs.mwrap.wuffs.aux;', '',
           'export import mcpplibs.mwrap.wuffs.base;', '', 'export namespace wuffs_aux {']
    out += [f'using wuffs_aux::{n};' for n in sf.aux.get('wuffs_aux', [])]
    for scope in sorted(k for k in sf.aux if k != 'wuffs_aux'):
        inner = scope.split('::', 1)[1]
        out += ['', f'namespace {inner} {{']
        out += [f'using {scope}::{n};' for n in sf.aux[scope]]
        out.append(f'}}  // namespace {inner}')
    out.append('}  // namespace wuffs_aux')
    return '\n'.join(out) + '\n'


def macros_unit(sf) -> str:
    inline_names = {f.name for fs in sf.inlines.values() for f in fs}
    out = [BANNER, '//',
           '// mcpplibs.mwrap.wuffs.macros — the macros of <wuffs-v0.3.c> (a named module',
           '// cannot export a macro), under their original names in',
           f'// {NAMESPACE}::macros:',
           '//',
           '//   - every macro that is a constant (WUFFS_BASE__PIXEL_FORMAT__*,',
           '//     WUFFS_INITIALIZE__*, the quirks, WUFFS_VERSION …) as `inline constexpr`',
           '//     of its macro\'s type; the strings as `const char[]`;',
           '//   - every macro that names a function (wuffs_base__load_u32le__no_bounds_check',
           '//     and the like) as a constexpr pointer to that function.',
           '//',
           '// tools/check_exports.py accounts for every macro; the rest (attributes, the',
           '// include guard, the type-building WUFFS_BASE__SLICE(T) …) stay in',
           '// <mwrap/wuffs/macros.hpp>.',
           'module;', f'#include <{HEADER}>', '', 'namespace mwrap_wuffs_capture {']
    for name, kind in sf.constants.items():
        if kind == 'string':
            out.append(f'inline constexpr char value_{name}[] = {name};')
        else:
            out.append(f'inline constexpr auto value_{name} = {name};')
    out.append('}  // namespace mwrap_wuffs_capture')
    out += [f'#undef {n}' for n in list(sf.constants) + list(sf.aliases)]
    out += ['', 'export module mcpplibs.mwrap.wuffs.macros;', '',
            'import mcpplibs.mwrap.wuffs.base;', '', f'export namespace {NAMESPACE}::macros {{', '']
    for name, kind in sf.constants.items():
        if kind == 'string':
            out.append(f'inline constexpr auto& {name} = mwrap_wuffs_capture::value_{name};')
        else:
            out.append(f'inline constexpr auto {name} = mwrap_wuffs_capture::value_{name};')
    out += ['', '// macros that name a function']
    for name, target in sf.aliases.items():
        owner = f'{NAMESPACE}::' if target in inline_names else '::'
        out.append(f'inline constexpr auto {name} = &{owner}{target};')
    out.append(f'\n}}  // namespace {NAMESPACE}::macros')
    return '\n'.join(out) + '\n'


def root_unit(sf) -> str:
    out = [BANNER, '//',
           '// mcpplibs.mwrap.wuffs — Wuffs (memory-safe decoders for untrusted formats) as',
           '// C++ modules: every package, the wuffs_aux C++ API and the macro mappings.',
           'export module mcpplibs.mwrap.wuffs;', '']
    out += [f'export import mcpplibs.mwrap.wuffs.{pkg};' for pkg in sf.packages]
    out += ['export import mcpplibs.mwrap.wuffs.aux;', 'export import mcpplibs.mwrap.wuffs.macros;']
    return '\n'.join(out) + '\n'


def surface_test(sf) -> str:
    inline_names = {f.name for fs in sf.inlines.values() for f in fs}
    out = [BANNER, '//',
           '// The whole mapped surface, checked by the compiler: this translation unit',
           '// includes <wuffs-v0.3.c> (the side header) and imports the module, then',
           '//   - each adapted static inline function has upstream\'s exact signature;',
           '//   - each constant of the macros module equals its macro, with its type',
           '//     (the macros are captured, then set aside so the names are reachable);',
           '//   - each macro that names a function is a pointer of that function\'s type;',
           '//   - each exported global of every package is the header\'s entity.',
           '#include <mwrap/wuffs/macros.hpp>', '', '#include <string_view>', '#include <type_traits>', '',
           'namespace raw {']
    for name, kind in sf.constants.items():
        out.append(f'inline constexpr {"char" if kind == "string" else "auto"} value_{name}{"[]" if kind == "string" else ""} = {name};')
    out.append('}  // namespace raw')
    out += [f'#undef {n}' for n in list(sf.constants) + list(sf.aliases)]
    out += ['', 'import mcpplibs.mwrap.wuffs;', '', 'namespace w = mcpplibs::mwrap::wuffs;',
            'namespace m = mcpplibs::mwrap::wuffs::macros;', '', '// adapted static inline functions']
    for fs in sf.inlines.values():
        for f in fs:
            out.append(f'static_assert(std::is_same_v<decltype(&w::{f.name}), decltype(&::{f.name})>);')
    out.append('\n// constants')
    for name, kind in sf.constants.items():
        if kind == 'string':
            out.append(f'static_assert(std::string_view(m::{name}) == std::string_view(raw::value_{name}));')
        else:
            out.append(f'static_assert(m::{name} == raw::value_{name} && '
                       f'std::is_same_v<std::remove_cv_t<decltype(m::{name})>, std::remove_cv_t<decltype(raw::value_{name})>>);')
    out.append('\n// macros that name a function')
    for name, target in sf.aliases.items():
        owner = 'w::' if target in inline_names else '::'
        out.append(f'static_assert(std::is_same_v<std::remove_cv_t<decltype(m::{name})>, decltype(&::{target})> && '
                   f'm::{name} == &{owner}{target});')
    out.append('\n// exported functions are the header\'s')
    for pkg in sf.packages:
        for name in sf.functions.get(pkg, []):
            out.append(f'static_assert(&::{name} != nullptr);')
    out += ['', 'int main() { return 0; }']
    return '\n'.join(out) + '\n'


def render(sf) -> dict[str, str]:
    files = {f'src/{pkg}.cppm': package_unit(sf, pkg) for pkg in sf.packages}
    files['src/wuffs_aux.cppm'] = aux_unit(sf)  # not aux.cppm: AUX is a reserved file name on Windows
    files['src/macros.cppm'] = macros_unit(sf)
    files['src/wuffs.cppm'] = root_unit(sf)
    files['tests/surface_test.cpp'] = surface_test(sf)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--clang')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    files = render(surface(fetch(root), find_clang(args.clang)))
    stale = []
    for relative, text in files.items():
        path = root / relative
        current = path.read_text(encoding='utf-8') if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(relative)
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
            print('wrote', relative)
    extra = sorted(p.relative_to(root).as_posix() for p in (root / 'src').glob('*.cppm')
                   if p.relative_to(root).as_posix() not in files)
    if extra:
        stale += [f'{e} (not generated)' for e in extra]
    if stale:
        sys.exit('not what tools/gen_exports.py writes: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
