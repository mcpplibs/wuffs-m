#!/usr/bin/env python3
"""The public surface of Wuffs' release/c/wuffs-v0.3.c, from the pinned release.

Shared by tools/gen_exports.py (which writes the module units) and
tools/check_exports.py (which audits them). The file comes from the upstream
tag archive, downloaded once into target/upstream and checked against
upstream/documents.json: the same bytes compat.wuffs builds.

The file is ~11,400 lines of interface generated by Wuffs' own compiler, with
C++ member functions inside its structs and the wuffs_aux namespace, so it is
read by the compiler that builds it, not by patterns:

  - declarations: `clang++ -Xclang -ast-dump=json -Xclang -ast-dump-filter=wuffs`
    in C++ mode (every Wuffs name contains "wuffs"; the filter keeps the dump
    to them). A dumped declaration nested in another dumped one is not
    top-level; what remains is classified by kind and storage class.
  - macros: `clang++ -E -dD`, whose line markers tell which file defines each.
    Every object-like macro is then evaluated as a constant in one probe
    translation unit; the diagnostics name those that are not constants.

Upstream's packages (base, png, gif, json …) are the module grouping:
`wuffs_<package>__name` belongs to package <package>.
"""
from dataclasses import dataclass, field
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import urllib.request

RELEASE_FILE = 'release/c/wuffs-v0.3.c'
HEADER = 'wuffs-v0.3.c'


def fetch(root: Path) -> Path:
    """The pinned tag archive, extracted under target/upstream; its top directory."""
    pins = json.loads((root / 'upstream/documents.json').read_text(encoding='utf-8'))
    cache = root / 'target/upstream'
    cache.mkdir(parents=True, exist_ok=True)
    archive = cache / 'wuffs-release.tar.gz'
    if not archive.exists() or hashlib.sha256(archive.read_bytes()).hexdigest() != pins['upstream_sha256']:
        print('+ fetch', pins['upstream'], flush=True)
        with urllib.request.urlopen(pins['upstream'], timeout=300) as response:
            archive.write_bytes(response.read())
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    if digest != pins['upstream_sha256']:
        sys.exit(f'upstream archive checksum {digest} != {pins["upstream_sha256"]}')
    with tarfile.open(archive) as tar:
        top = tar.getmembers()[0].name.split('/')[0]
        if not (cache / top / RELEASE_FILE).exists():
            tar.extractall(cache, filter='data')
    return cache / top


def find_clang(explicit: str | None = None) -> str:
    """clang++: --clang, $CLANGXX, PATH, then the llvm toolchain mcpp installs."""
    for candidate in (explicit, os.environ.get('CLANGXX'), shutil.which('clang++')):
        if candidate:
            return candidate
    homes = [Path(os.environ[v]) for v in ('MCPP_HOME', 'XLINGS_HOME') if os.environ.get(v)]
    homes += [Path.home() / '.mcpp', Path.home() / '.xlings']
    for home in homes:
        found = sorted(home.glob('**/xim-x-llvm/*/bin/clang++*'))
        if found:
            return str(found[-1])
    sys.exit('clang++ not found: pass --clang or set CLANGXX (the audit reads clang\'s AST)')


@dataclass
class Function:
    name: str
    result: str                 # return type, as clang spells it
    params: list[tuple[str, str]]  # (type, name)
    package: str


@dataclass
class Surface:
    packages: list[str] = field(default_factory=list)
    functions: dict[str, list[str]] = field(default_factory=dict)   # package -> external functions
    inlines: dict[str, list[Function]] = field(default_factory=dict)  # package -> static inline functions
    types: dict[str, list[str]] = field(default_factory=dict)       # package -> typedef names
    tags: dict[str, list[str]] = field(default_factory=dict)        # package -> struct tags
    data: dict[str, list[str]] = field(default_factory=dict)        # package -> extern const objects
    aux: dict[str, list[str]] = field(default_factory=dict)         # wuffs_aux scope -> names
    constants: dict[str, str] = field(default_factory=dict)         # macro -> 'number' | 'string'
    aliases: dict[str, str] = field(default_factory=dict)           # macro -> the function it names
    other_macros: dict[str, str] = field(default_factory=dict)      # macro -> its definition (not a constant)
    function_macros: dict[str, str] = field(default_factory=dict)   # function-like macro -> its parameters


def package_of(name: str) -> str:
    m = re.match(r'(?:sizeof__)?wuffs_([a-z0-9]+)__', name)  # sizeof__wuffs_png__decoder() is png's
    if not m:
        raise SystemExit(f'not a Wuffs package name: {name}')
    return m.group(1)


def _decls(clang: str, include: Path) -> list[dict]:
    with tempfile.TemporaryDirectory() as tmp:
        tu = Path(tmp) / 'surface.cc'
        tu.write_text(f'#include <{HEADER}>\n')
        out = subprocess.run([clang, '-std=c++23', '-fsyntax-only', '-I', str(include),
                              '-Xclang', '-ast-dump=json', '-Xclang', '-ast-dump-filter=wuffs', str(tu)],
                             capture_output=True, text=True, check=True).stdout
    decoder = json.JSONDecoder()
    objects, i = [], 0
    while (j := out.find('{', i)) >= 0:
        obj, i = decoder.raw_decode(out, j)
        objects.append(obj)
    nested: set[str] = set()

    def walk(node):
        for child in node.get('inner') or []:
            nested.add(child.get('id'))
            walk(child)
    for obj in objects:
        walk(obj)
    return [o for o in objects if o.get('id') not in nested]


def _result_type(function_type: str) -> str:
    depth = 0
    for i, ch in enumerate(function_type):
        if ch in '<[':
            depth += 1
        elif ch in '>]':
            depth -= 1
        elif ch == '(' and depth == 0:
            return function_type[:i].strip()
    raise SystemExit(f'cannot read the result type of {function_type!r}')


def _macros(clang: str, include: Path) -> list[tuple[str, str | None, str]]:
    """(name, parameters or None, body) of every macro the release file defines, in order."""
    with tempfile.TemporaryDirectory() as tmp:
        tu = Path(tmp) / 'macros.cc'
        tu.write_text(f'#include <{HEADER}>\n')
        out = subprocess.run([clang, '-std=c++23', '-E', '-dD', '-I', str(include), str(tu)],
                             capture_output=True, text=True, check=True).stdout
    current, found = None, []
    for line in out.splitlines():
        marker = re.match(r'# \d+ "([^"]+)"', line)
        if marker:
            current = marker.group(1)
            continue
        if current and current.replace('\\', '/').endswith('/' + HEADER):
            d = re.match(r'#define (\w+)(\(([^)]*)\))?\s*(.*)', line)
            if d:
                found.append((d.group(1), d.group(3) if d.group(2) else None, d.group(4).strip()))
    return found


def _probe_constants(clang: str, include: Path, names: list[str]) -> set[str]:
    """The macros of `names` that are constant expressions (one probe TU, diagnostics by line)."""
    with tempfile.TemporaryDirectory() as tmp:
        tu = Path(tmp) / 'probe.cc'
        lines = [f'#include <{HEADER}>', 'namespace probe {']
        first = len(lines) + 1
        lines += [f'constexpr auto value_{n} = ({n});' for n in names]
        lines.append('}')
        tu.write_text('\n'.join(lines) + '\n')
        out = subprocess.run([clang, '-std=c++23', '-fsyntax-only', '-ferror-limit=0', '-I', str(include), str(tu)],
                             capture_output=True, text=True)
    bad = {int(m.group(1)) for m in re.finditer(r'probe\.cc:(\d+):\d+: error', out.stderr)}
    return {n for i, n in enumerate(names) if first + i not in bad}


def surface(upstream: Path, clang: str) -> Surface:
    include = upstream / 'release/c'
    s = Surface()
    functions: set[str] = set()
    for d in _decls(clang, include):
        kind, name = d['kind'], d.get('name')
        if kind == 'CXXMethodDecl':
            continue  # an out-of-class definition of a member: it comes with its struct
        if kind == 'NamespaceDecl':
            assert name == 'wuffs_aux', name
            for child in d.get('inner') or []:
                if child.get('isImplicit') or not child.get('name'):
                    continue
                if child['kind'] == 'NamespaceDecl':
                    for grand in child.get('inner') or []:
                        if not grand.get('isImplicit') and grand.get('name'):
                            s.aux.setdefault('wuffs_aux::' + child['name'], []).append(grand['name'])
                elif child['kind'] in ('CXXRecordDecl', 'FunctionDecl', 'VarDecl', 'TypeAliasDecl', 'TypedefDecl'):
                    s.aux.setdefault('wuffs_aux', []).append(child['name'])
                else:
                    raise SystemExit(f'unexpected {child["kind"]} {child["name"]} in wuffs_aux')
            continue
        if not name:
            continue  # an anonymous struct, exported through its typedef
        pkg = package_of(name)
        if kind == 'FunctionDecl':
            functions.add(name)
            if d.get('storageClass') == 'static':
                params = [(p['type']['qualType'], p.get('name') or f'a{i}')
                          for i, p in enumerate(c for c in d.get('inner') or [] if c['kind'] == 'ParmVarDecl')]
                s.inlines.setdefault(pkg, []).append(
                    Function(name, _result_type(d['type']['qualType']), params, pkg))
            else:
                s.functions.setdefault(pkg, []).append(name)
        elif kind == 'TypedefDecl':
            s.types.setdefault(pkg, []).append(name)
        elif kind in ('CXXRecordDecl', 'RecordDecl'):
            s.tags.setdefault(pkg, []).append(name)
        elif kind == 'VarDecl':
            if d.get('storageClass') != 'extern':
                raise SystemExit(f'{name}: a variable that is not extern ({d.get("storageClass")})')
            s.data.setdefault(pkg, []).append(name)
        else:
            raise SystemExit(f'unexpected top-level {kind} {name}')
    for table in (s.functions, s.types, s.tags, s.data, s.aux):
        for key in table:
            table[key] = sorted(set(table[key]))
    for key in s.inlines:
        s.inlines[key].sort(key=lambda f: f.name)
    # Packages in upstream's order of appearance would vary with the file; sort, base first.
    names = set(s.functions) | set(s.inlines) | set(s.types) | set(s.tags) | set(s.data)
    s.packages = ['base'] + sorted(names - {'base'})

    macros = _macros(clang, include)
    objects = [(n, body) for n, params, body in macros if params is None]
    s.function_macros = {n: params for n, params, _ in macros if params is not None}
    candidates = []
    for name, body in objects:
        if body in functions:
            s.aliases[name] = body
        elif body:
            candidates.append(name)
        else:
            s.other_macros[name] = body
    constant = _probe_constants(clang, include, candidates)
    bodies = dict(objects)
    for name in candidates:
        if name in constant:
            s.constants[name] = 'string' if bodies[name].startswith('"') else 'number'
        else:
            s.other_macros[name] = bodies[name]
    return s


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--clang')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    sf = surface(fetch(root), find_clang(args.clang))
    for pkg in sf.packages:
        print(f'{pkg:8} {len(sf.functions.get(pkg, [])):4} functions {len(sf.inlines.get(pkg, [])):4} inline '
              f'{len(sf.types.get(pkg, [])):3} types {len(sf.tags.get(pkg, [])):3} tags {len(sf.data.get(pkg, [])):3} data')
    print('wuffs_aux:', {k: len(v) for k, v in sf.aux.items()})
    print(f'macros: {len(sf.constants)} constants, {len(sf.aliases)} aliases of functions, '
          f'{len(sf.other_macros)} other, {len(sf.function_macros)} function-like')
    print('other:', sf.other_macros)
